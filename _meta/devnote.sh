#!/usr/bin/env bash
# devnote — AI-agnostic helper for the devnotes repo.
# Works with bash 3.2 (macOS default) and newer. No dependencies beyond git + coreutils.
#
#   devnote tree                      list folders and notes
#   devnote prompt [--print]          build the distill prompt (rules + templates + tree) → clipboard
#   devnote save [FILE|-] [--force] [--no-push]
#                                     save an AI answer with one or more notes (clipboard by default)
#                                     → lint → index → commit → push
#   devnote publish [--force] [--no-push] [-m MSG]
#                                     lint changed notes → index → commit → push
#   devnote index                     rebuild the index in README.md
#   devnote lint [FILE...]            check notes against AGENTS.md (default: changed notes)
set -euo pipefail

ROOT="$(cd "$(dirname "$0")/.." && pwd)"
cd "$ROOT"

PATH_RE='^[a-z0-9][a-z0-9-]*/[a-z0-9][a-z0-9-]*\.md$'

die()  { printf 'devnote: %s\n' "$*" >&2; exit 1; }
info() { printf '%s\n' "$*" >&2; }

usage() { sed -n '2,13p' "$0" | sed 's/^# \{0,1\}//'; }

# ---------- clipboard -------------------------------------------------------
clip_copy() {
  if command -v pbcopy >/dev/null 2>&1; then pbcopy
  elif command -v wl-copy >/dev/null 2>&1; then wl-copy
  elif command -v xclip >/dev/null 2>&1; then xclip -selection clipboard
  else return 1; fi
}
clip_paste() {
  if command -v pbpaste >/dev/null 2>&1; then pbpaste
  elif command -v wl-paste >/dev/null 2>&1; then wl-paste --no-newline
  elif command -v xclip >/dev/null 2>&1; then xclip -selection clipboard -o
  else return 1; fi
}
has_clipboard() { command -v pbcopy >/dev/null 2>&1 || command -v wl-copy >/dev/null 2>&1 || command -v xclip >/dev/null 2>&1; }

# ---------- repo listing ----------------------------------------------------
note_dirs()  { find . -mindepth 1 -maxdepth 1 -type d ! -name '.*' ! -name '_*' | sed 's|^\./||' | LC_ALL=C sort; }
note_files() { find . -mindepth 2 -maxdepth 2 -type f -name '*.md' ! -path './.*' ! -path './_*' | sed 's|^\./||' | LC_ALL=C sort; }

# Title = first "# " heading outside front matter and code fences.
title_of() {
  awk '
    NR==1 && /^---[[:space:]]*$/ { fm=1; next }
    fm && /^---[[:space:]]*$/    { fm=0; next }
    fm                           { next }
    /^(```|~~~)/                 { code=!code; next }
    !code && /^# /               { sub(/^# +/, ""); print; exit }
  ' "$1"
}

cmd_tree() {
  local d f
  for d in $(note_dirs); do
    printf '%s/\n' "$d"
    for f in $(note_files | grep "^$d/" || true); do
      printf '  %-40s %s\n' "${f#*/}" "$(title_of "$f")"
    done
  done
}

# ---------- index -----------------------------------------------------------
cmd_index() {
  local tmp out d f n
  tmp="$(mktemp)"; out="$(mktemp)"
  n=$(note_files | grep -c . || true)
  {
    echo '<!-- index:start -->'
    echo '<!-- Generated by `_meta/devnote.sh index`. Do not edit by hand. -->'
    echo
    echo "_${n} notes_"
    for d in $(note_dirs); do
      echo
      echo "### ${d}"
      echo
      for f in $(note_files | grep "^$d/" || true); do
        echo "- [$(title_of "$f")](${f})"
      done
    done
    echo
    echo '<!-- index:end -->'
  } > "$tmp"

  [ -f README.md ] || printf '# devnotes\n' > README.md
  if grep -q '<!-- index:start -->' README.md; then
    awk -v f="$tmp" '
      /<!-- index:start -->/ { while ((getline l < f) > 0) print l; skip=1; next }
      /<!-- index:end -->/   { skip=0; next }
      !skip                  { print }
    ' README.md > "$out"
  else
    { cat README.md; printf '\n## Index\n\n'; cat "$tmp"; } > "$out"
  fi
  mv "$out" README.md; rm -f "$tmp"
  info "index: ${n} notes"
}

# ---------- lint ------------------------------------------------------------
# Prints "ERROR …" / "WARN …" lines. Returns 1 if any ERROR.
lint_file() {
  local f="$1" errs=0 warned=0 type words h1
  e() { printf '  ERROR %s: %s\n' "$f" "$*"; errs=1; }
  w() { printf '  WARN  %s: %s\n' "$f" "$*"; warned=1; }

  printf '%s\n' "$f" | grep -Eq "$PATH_RE" || e "path must be folder/kebab-case.md (one level, lowercase)"
  in_table "${f%%/*}" || e "folder '${f%%/*}' is not in the AGENTS.md §3 table (use an existing name or add a row)"
  [ "$(head -n1 "$f")" = "---" ] || e "missing front matter (must start with ---)"
  type=$(awk 'NR>1 && /^---/{exit} /^type:/{print $2; exit}' "$f")
  case "$type" in concept|howto|comparison) ;; *) e "front matter 'type' must be concept|howto|comparison";; esac
  for k in tags created updated; do
    awk -v k="$k" 'NR>1 && /^---/{exit} $0 ~ "^"k":"{found=1} END{exit !found}' "$f" || e "front matter missing '$k'"
  done
  h1=$(awk '/^(```|~~~)/{c=!c; next} !c && /^# /{n++} END{print n+0}' "$f")
  [ "$h1" = "1" ] || e "needs exactly one '# Title' heading (found $h1)"
  grep -q 'TL;DR' "$f"          || e "missing TL;DR line"
  grep -q '^## Sources' "$f"    || e "missing '## Sources' section"
  grep -q '<!--' "$f"           && e "template guidance comment left in (<!-- … -->)"

  # Body word count, excluding front matter and code blocks.
  words=$(awk 'NR==1&&/^---/{fm=1;next} fm&&/^---/{fm=0;next} fm{next} /^(```|~~~)/{c=!c;next} !c' "$f" | wc -w | tr -d ' ')
  [ "$words" -le 1500 ] || w "${words} words — consider splitting into linked notes (AGENTS.md §5)"

  # Patterns that look like real data (warnings only).
  local real
  real=$(grep -Eo '[A-Za-z0-9._%+-]+@[A-Za-z0-9.-]+\.[A-Za-z]{2,}' "$f" \
         | grep -Eiv '@(example\.(com|org|net)|users\.noreply\.github\.com)$|\.(example|test|invalid|localhost)$|^git@' | sort -u | tr '\n' ' ' || true)
  [ -z "$real" ] || w "email(s) not on example.com: $real"
  grep -Eq '(\+62|(^|[^0-9])0)8[0-9]{2}[- ]?[0-9]{3,4}[- ]?[0-9]{3,5}' "$f" && w "looks like a phone number"
  real=$(grep -Eo '([0-9]{1,3}\.){3}[0-9]{1,3}' "$f" \
         | grep -Ev '^(127\.|0\.0\.0\.0|10\.|192\.168\.|172\.(1[6-9]|2[0-9]|3[01])\.|192\.0\.2\.|198\.51\.100\.|203\.0\.113\.)' \
         | sort -u | tr '\n' ' ' || true)
  [ -z "$real" ] || w "public IP address(es): $real (use 192.0.2.x / 198.51.100.x / 203.0.113.x)"
  grep -Eiq '[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}' "$f" \
    && w "contains a UUID — use simple fake IDs (1, 2, 3) unless the UUID itself is the lesson"
  grep -Eiq '[a-z0-9-]+\.(internal|corp|lan|svc\.cluster\.local)([^a-z0-9]|$)|(^|[^a-z0-9])prod[-_][a-z0-9]+' "$f" \
    && w "looks like an internal hostname or prod resource name"

  # Private words, kept outside the repo.
  local deny="${DEVNOTE_DENYLIST:-$HOME/.config/devnote/denylist}" hits=""
  if [ -f "$deny" ]; then
    hits=$({ grep -v '^[[:space:]]*#' "$deny" || true; } | while IFS= read -r word; do
      [ -n "$word" ] || continue
      if grep -qiF -- "$word" "$f"; then printf '"%s" ' "$word"; fi
    done)
    [ -z "$hits" ] || e "contains private term(s) from $deny: $hits"
  fi

  grep -Eiq "as (we )?discussed|you asked|great question|the ai (said|suggested)|in this (note|article)" "$f" \
    && w "looks like chat leftovers ('as discussed', 'you asked', …)"
  awk '/^(```|~~~)/{c=!c;next} !c' "$f" | grep -Eiwq "yang|dengan|untuk|tidak|adalah|karena|kalau|bisa" \
    && w "possible Indonesian text outside code (notes are English only)"
  [ $errs = 1 ] || [ $warned = 1 ] || printf '  ok    %s (%s words)\n' "$f" "$words"
  return $errs
}

# Is FOLDER listed in the folder table of AGENTS.md?
in_table() { grep -q "^| \`$1\` |" AGENTS.md; }

changed_notes() {
  git status --porcelain -uall 2>/dev/null | sed 's/^...//; s/.* -> //' | { grep -E "$PATH_RE" || true; } | { grep -v '^_' || true; } | while read -r p; do
    if [ -f "$p" ]; then echo "$p"; fi
  done
}

cmd_lint() {
  local files rc=0 f
  if [ $# -gt 0 ]; then files="$*"; else files="$(changed_notes)"; fi
  [ -n "$files" ] || { info "lint: no changed notes"; return 0; }
  for f in $files; do lint_file "$f" || rc=1; done
  return $rc
}

# ---------- publish ---------------------------------------------------------
cmd_publish() {
  local force=0 push=1 msg="" notes n f status verb
  while [ $# -gt 0 ]; do
    case "$1" in
      --force) force=1;; --no-push) push=0;;
      -m) shift; msg="${1:-}";;
      *) die "publish: unknown option $1";;
    esac; shift
  done

  notes="$(changed_notes)"
  if [ -n "$notes" ]; then
    info "lint:"
    if ! cmd_lint $notes; then
      [ $force = 1 ] || die "lint errors above. Fix them, or re-run with --force."
    fi
  fi

  cmd_index
  git add -A
  git diff --cached --quiet && { info "nothing to publish"; return 0; }

  if [ -z "$msg" ]; then
    n=$(printf '%s\n' "$notes" | grep -c . || true)
    if [ "$n" = "1" ]; then
      f="$notes"
      status=$(git diff --cached --name-status -- "$f" | cut -c1)
      if [ "$status" = "A" ]; then verb=add; else verb=update; fi
      msg="docs(${f%%/*}): ${verb} $(basename "$f" .md)"
    elif [ "$n" -gt 1 ]; then
      if [ "$(printf '%s\n' "$notes" | cut -d/ -f1 | sort -u | grep -c .)" = "1" ]; then
        msg="docs(${notes%%/*}): add or update ${n} notes"
      else
        msg="docs: add or update ${n} notes"
      fi
    else
      msg="chore: update devnotes meta"
    fi
  fi

  git commit -q -m "$msg"
  info "committed: $msg"
  if [ $push = 1 ]; then
    git pull -q --rebase --autostash || die "pull failed; resolve, then run: git push"
    git push -q && info "pushed"
  fi
}

# ---------- save ------------------------------------------------------------
cmd_save() {
  local src="" force=0 push=1 raw tmpd i path seg n ans
  while [ $# -gt 0 ]; do
    case "$1" in
      --force) force=1;; --no-push) push=0;;
      -) src="-";;
      -*) die "save: unknown option $1";;
      *) src="$1";;
    esac; shift
  done

  if [ "$src" = "-" ]; then raw="$(cat)"
  elif [ -n "$src" ]; then [ -f "$src" ] || die "no such file: $src"; raw="$(cat "$src")"
  else raw="$(clip_paste)" || die "no clipboard tool; pass a file or '-' for stdin"
  fi

  # Split the input into one segment per "<!-- path: … -->" line.
  # Drops CR, 4+-backtick fences (the AI's wrapper), and a single 3-backtick ```markdown wrapper.
  tmpd="$(mktemp -d)"
  printf '%s\n' "$raw" | tr -d '\r' | awk -v d="$tmpd" '
    /^````+[[:space:]]*(markdown|md)?[[:space:]]*$/ { fenced=1; infence=!infence; next }
    fenced && !infence                              { next }
    /^```(markdown|md)[[:space:]]*$/ && !n         { wrap=1; next }
    /^<!--[[:space:]]*path:[[:space:]]*[^[:space:]]+[[:space:]]*-->/ {
      if (n) close(f)
      n++; f = d "/" n ".md"
      p = $0; sub(/^<!--[[:space:]]*path:[[:space:]]*/, "", p); sub(/[[:space:]]*-->.*$/, "", p)
      print p > (d "/" n ".path"); close(d "/" n ".path")
      started=0; next
    }
    n { if (!started && $0 ~ /^[[:space:]]*$/) next; started=1; print > f }
    END { print n+0 > (d "/count"); if (wrap) print 1 > (d "/wrap") }
  '
  n="$(cat "$tmpd/count")"
  [ "$n" -gt 0 ] || { rm -rf "$tmpd"; die "no '<!-- path: folder/file.md -->' line found"; }

  # Tidy each segment: drop trailing blank lines (and the closing ``` of a 3-backtick wrapper on the last one).
  i=1
  while [ "$i" -le "$n" ]; do
    seg="$tmpd/$i.md"
    awk '{a[NR]=$0} END{m=NR; while(m>0 && a[m] ~ /^[[:space:]]*$/) m--; for(i=1;i<=m;i++) print a[i]}' "$seg" > "$seg.t"
    if [ "$i" = "$n" ] && [ -f "$tmpd/wrap" ] && [ "$(tail -n1 "$seg.t")" = '```' ]; then
      sed '$d' "$seg.t" > "$seg.u" && mv "$seg.u" "$seg.t"
    fi
    mv "$seg.t" "$seg"
    path="$(cat "$tmpd/$i.path")"
    printf '%s\n' "$path" | grep -Eq "$PATH_RE" || { rm -rf "$tmpd"; die "invalid path '$path' (folder/kebab-case.md, one level)"; }
    case "$path" in _*) rm -rf "$tmpd"; die "notes cannot live in '_' folders";; esac
    i=$((i+1))
  done

  git pull -q --rebase --autostash 2>/dev/null || info "warning: git pull failed; continuing offline"

  i=1
  while [ "$i" -le "$n" ]; do
    seg="$tmpd/$i.md"; path="$(cat "$tmpd/$i.path")"
    in_table "${path%%/*}" || info "warning: folder '${path%%/*}' is not in AGENTS.md §3 — add a row there, or lint will fail"
    if [ -f "$path" ] && [ $force = 0 ]; then
      info "exists: $path — diff:"
      diff -u "$path" "$seg" | head -n 60 >&2 || true
      if [ -t 0 ] && [ "$src" != "-" ]; then
        printf 'Overwrite %s? [y/N] ' "$path" >&2; read -r ans
        case "$ans" in y|Y) ;; *) rm -rf "$tmpd"; die "aborted";; esac
      else
        rm -rf "$tmpd"; die "$path exists; re-run with --force to overwrite"
      fi
    fi
    mkdir -p "${path%%/*}"
    cp "$seg" "$path"
    info "wrote $path"
    i=$((i+1))
  done
  rm -rf "$tmpd"

  if [ $push = 1 ]; then cmd_publish; else cmd_publish --no-push; fi
}

# ---------- prompt ----------------------------------------------------------
cmd_prompt() {
  local print=0 out t
  [ "${1:-}" = "--print" ] && print=1
  out="$(
    sed "s/{{TODAY}}/$(date +%Y-%m-%d)/g" _meta/prompts/distill.md
    printf '\n\n---\n\n# Repository rules (AGENTS.md)\n\n'
    cat AGENTS.md
    for t in _meta/templates/*.md; do
      printf '\n\n---\n\n# Template: %s\n\n````markdown\n' "$(basename "$t" .md)"
      cat "$t"
      printf '````\n'
    done
    printf '\n\n---\n\n# Current notes (folder/file  title)\n\n```\n'
    cmd_tree
    printf '```\n'
  )"
  if [ $print = 0 ] && has_clipboard; then
    printf '%s\n' "$out" | clip_copy
    info "copied distill prompt to clipboard ($(printf '%s' "$out" | wc -c | tr -d ' ') chars) — paste it at the end of your AI chat"
  else
    printf '%s\n' "$out"
  fi
}

# ---------- main ------------------------------------------------------------
cmd="${1:-help}"; [ $# -gt 0 ] && shift
case "$cmd" in
  tree)    cmd_tree ;;
  prompt)  cmd_prompt "$@" ;;
  save)    cmd_save "$@" ;;
  publish) cmd_publish "$@" ;;
  index)   cmd_index ;;
  lint)    cmd_lint "$@" ;;
  help|-h|--help) usage ;;
  *) usage; exit 1 ;;
esac
